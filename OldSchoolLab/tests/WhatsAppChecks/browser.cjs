const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_CORE || 'playwright-core');
(async () => {
    const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(() => {
        window.testLinks = [];
        const fake = { closed: false, focus() {}, close() { this.closed = true; } };
        Object.defineProperty(fake, 'location', { set(value) { window.testLinks.push(String(value)); } });
        window.open = () => window.testBlocked ? null : fake;
    });
    try {
        await page.goto('http://127.0.0.1:5187/Records?WhatsAppFilter=unsent');
        await page.waitForFunction(() => document.querySelector('#waMetrics')?.textContent.includes('Números'));
        await page.click('#waSettingsToggle');
        await page.fill('#waMessage', 'Hola & reactivación 🧪\nConsulta envío a tu ciudad.');
        await page.click('#waSaveMessage');
        await page.waitForFunction(() => document.querySelector('#waFeedback').textContent === 'Mensaje guardado.');
        await page.check('#waSelectAll');
        assert.equal(await page.locator('#waSelectedCount').textContent(), '2', 'selection excludes duplicate phones');
        assert.equal(await page.locator('.wa-select:disabled').count(), 1, 'blocked contact remains disabled');
        await page.click('#waStart');
        await page.waitForSelector('#waPreview:not([hidden])');
        assert.match(await page.locator('#waPreviewText').textContent(), /Se incluirán 2 números/);
        await page.evaluate(() => window.testBlocked = true);
        await page.click('#waConfirm');
        await page.waitForSelector('#waFeedback a');
        assert.match(await page.locator('#waFeedback a').getAttribute('href'), /^https:\/\/wa\.me\//, 'popup-blocked fallback retains a usable link');
        await page.evaluate(() => window.testBlocked = false);
        await page.click('#waOpen');
        await page.waitForFunction(() => window.testLinks.length === 1 && !document.querySelector('#waSent').disabled);
        const firstLink = await page.evaluate(() => window.testLinks[0]);
        assert.match(firstLink, /^https:\/\/wa\.me\/5190000000[13]\?text=/);
        assert.equal(new URL(firstLink).searchParams.get('text'), 'Hola & reactivación 🧪\nConsulta envío a tu ciudad.');
        assert.match(await page.locator('#waProgress').textContent(), /0 de 2 enviados/);
        await page.click('#waSent');
        await page.waitForFunction(() => document.querySelector('#waProgress').textContent.includes('1 de 2 enviados') && window.testLinks.length === 2);
        const secondLink = await page.evaluate(() => window.testLinks[1]);
        assert.notEqual(new URL(firstLink).pathname, new URL(secondLink).pathname, 'next link targets a distinct number');
        await page.reload();
        await page.waitForFunction(() => document.querySelector('#waProgress')?.textContent.includes('1 de 2 enviados'));
        assert.equal(await page.evaluate(() => window.testLinks.length), 0, 'reload never reopens WhatsApp automatically');
        await page.click('#waPause');
        await page.waitForFunction(() => document.querySelector('#waProgress').textContent.includes('Pausada'));
        await page.reload();
        await page.waitForSelector('#waContinue:not([hidden])');
        await page.click('#waContinue');
        await page.waitForFunction(() => window.testLinks.length === 1 && !document.querySelector('#waSkip').disabled);
        assert.equal(await page.evaluate(() => window.testLinks[0]), secondLink, 'resume returns to the persisted pending number');
        await page.click('#waSkip');
        await page.waitForFunction(() => document.querySelector('#waProgress').textContent.includes('Terminada'));
        const noToken = await page.request.post('http://127.0.0.1:5187/Records?handler=WhatsAppMessage', { data: { message: 'missing CSRF' } });
        assert.equal(noToken.status(), 400, 'mutations require antiforgery token');
        await page.goto('http://127.0.0.1:5187/Records?WhatsAppFilter=sent');
        await page.waitForFunction(() => document.querySelector('#waMetrics')?.textContent.includes('Números'));
        const sentRows = await page.locator('.wa-select').count();
        assert.ok(sentRows === 1 || sentRows === 2, 'sent filter includes the sent phone and any historical duplicate');
        await page.locator('.wa-history').first().click();
        await page.waitForFunction(() => document.querySelector('#waHistoryBody').textContent.includes('Enviado (declarado)'));
        assert.match(await page.locator('#waHistoryBody').textContent(), /Hola & reactivación 🧪/);
        await page.evaluate(() => window.scrollTo(0, 0));
        await page.waitForTimeout(200);
        await page.screenshot({ path: process.env.WA_SCREENSHOT || 'whatsapp-desktop.png', fullPage: true });
        await page.setViewportSize({ width: 390, height: 844 });
        await page.evaluate(() => window.scrollTo(0, 0));
        await page.waitForTimeout(200);
        await page.screenshot({ path: (process.env.WA_SCREENSHOT || 'whatsapp-desktop.png').replace('desktop', 'mobile'), fullPage: true });
        await page.goto('http://127.0.0.1:5187/Records/Edit/4');
        await page.locator('details').first().evaluate(node => node.open = true);
        await page.selectOption('#CommercialConsent', 'Authorized');
        await page.fill('#ConsentEvidence', 'Autorización ficticia registrada desde Editar');
        await page.getByRole('button', { name: 'Guardar estado comercial', exact: true }).click();
        await page.waitForURL('**/Records/Edit/4*');
        await page.waitForSelector('#CommercialConsent', { state: 'attached' });
        assert.equal(await page.inputValue('#CommercialConsent'), 'Authorized', 'editing commercial state persists across redirect');
        await page.goto('http://127.0.0.1:5187/Records?ConsentFilter=authorized');
        await page.waitForFunction(() => document.querySelector('#waMetrics')?.textContent.includes('Números'));
        assert.equal(await page.locator('.wa-select').count(), 4, 'authorized filter sees the updated old record and phone duplicates');
        assert.deepEqual(errors, [], 'no browser runtime errors');
        console.log('PASS actual Razor UI: deduplicated selection, CSRF, encoded links, manual sent confirmation, next contact, reload, pause/resume, skip and persisted filters/history. No external WhatsApp page was opened.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
