const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_CORE || 'playwright-core');
(async () => {
    const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(() => {
        window.testLinks = [];
        const fake = { closed: false, focus() {}, close() { this.closed = true; } };
        Object.defineProperty(fake, 'location', { set(value) { window.testLinks.push(String(value)); } });
        window.open = () => window.testBlocked ? null : fake;
    });
    const ready = () => page.waitForFunction(() => document.querySelector('#waStart') && !document.querySelector('#waStart').disabled);
    const openModal = async () => { await ready(); await page.click('#waStart'); await page.waitForSelector('#waWorkspace.show'); await ready(); };
    try {
        await page.goto('http://127.0.0.1:5187/Records?WhatsAppFilter=no'); await ready();
        assert.equal(await page.locator('#ConsentFilter').count(), 0, 'commercial filter is removed');
        assert.deepEqual(await page.locator('#WhatsAppFilter option').allTextContents(), ['Todos', 'Sí', 'No'], 'single reactivated yes/no filter');
        assert.equal(await page.locator('.wa-select:not(:disabled)').count(), 3, 'old numbers are enabled without prior authorization steps');
        await page.check('#waSelectAll');
        assert.match(await page.locator('#waStart').textContent(), /WhatsApp masivo \(2\)/, 'duplicate phones count once');
        await openModal();
        assert.equal(await page.locator('#waContacts .list-group-item').count(), 2, 'modal lists all selected contacts before starting');
        await page.fill('#waMessage', 'Hola & reactivación 🧪\nConsulta envío a tu ciudad.');
        await page.click('#waSaveMessage');
        await page.waitForFunction(() => document.querySelector('#waFeedback').textContent === 'Mensaje guardado.');
        await page.evaluate(() => window.testBlocked = true);
        await page.click('#waConfirm');
        await page.waitForSelector('#waFeedback a');
        assert.match(await page.locator('#waFeedback a').getAttribute('href'), /^https:\/\/wa\.me\//, 'popup-blocked fallback remains usable');
        await page.evaluate(() => window.testBlocked = false);
        await page.click('#waOpen');
        await page.waitForFunction(() => window.testLinks.length === 1 && !document.querySelector('#waSent').disabled);
        const firstLink = await page.evaluate(() => window.testLinks[0]);
        assert.equal(new URL(firstLink).searchParams.get('text'), 'Hola & reactivación 🧪\nConsulta envío a tu ciudad.');
        assert.match(await page.locator('#waProgress').textContent(), /0 de 2 enviados/);
        assert.equal(await page.locator('.wa-row-state[data-sent="yes"]').count(), 0, 'opening link does not set reactivated yes');
        await page.screenshot({ path: process.env.WA_SCREENSHOT || 'whatsapp-modal-desktop.png', fullPage: true });
        await page.setViewportSize({ width: 390, height: 844 });
        await page.screenshot({ path: (process.env.WA_SCREENSHOT || 'whatsapp-modal-desktop.png').replace('desktop', 'mobile'), fullPage: true });
        await page.setViewportSize({ width: 1440, height: 1000 });
        await page.click('#waSent');
        await page.waitForFunction(() => document.querySelector('#waProgress').textContent.includes('1 de 2 enviados') && window.testLinks.length === 2);
        const secondLink = await page.evaluate(() => window.testLinks[1]);
        assert.notEqual(new URL(firstLink).pathname, new URL(secondLink).pathname);
        assert.equal(await page.locator('#waContacts .text-bg-success').count(), 1, 'modal marks sent item and keeps full queue');
        assert.ok(await page.locator('.wa-row-state[data-sent="yes"]').count() > 0, 'confirmed send updates reactivated immediately');
        await page.locator('#waWorkspace .btn-close').click();
        await page.waitForSelector('#waWorkspace', { state: 'hidden' });
        await openModal();
        assert.match(await page.locator('#waProgress').textContent(), /1 de 2 enviados/);
        assert.equal(await page.locator('#waContacts .list-group-item').count(), 2, 'closing modal preserves selection');
        await page.reload(); await ready();
        assert.equal(await page.evaluate(() => window.testLinks.length), 0, 'reload never opens WhatsApp');
        await openModal();
        assert.match(await page.locator('#waProgress').textContent(), /1 de 2 enviados/);
        await page.click('#waPause'); await page.waitForSelector('#waContinue:not([hidden])');
        await page.reload(); await openModal();
        await page.click('#waContinue');
        await page.waitForFunction(() => window.testLinks.length === 1 && !document.querySelector('#waSkip').disabled);
        assert.equal(await page.evaluate(() => window.testLinks[0]), secondLink, 'resume returns to the stored pending number');
        await page.click('#waSkip');
        await page.waitForFunction(() => document.querySelector('#waProgress').textContent.includes('Completado'));
        const noToken = await page.request.post('http://127.0.0.1:5187/Records?handler=WhatsAppMessage', { data: { message: 'missing CSRF' } });
        assert.equal(noToken.status(), 400);
        await page.goto('http://127.0.0.1:5187/Records?WhatsAppFilter=yes'); await ready();
        assert.ok(await page.locator('.wa-select').count() > 0, 'yes filter loads reactivated records');
        assert.equal(await page.locator('.wa-row-state[data-sent="no"]').count(), 0);
        await page.locator('.wa-history').first().click();
        await page.waitForFunction(() => document.querySelector('#waHistoryBody').textContent.includes('Hola & reactivación 🧪'));
        await page.goto('http://127.0.0.1:5187/Records/Edit/4');
        assert.equal(await page.locator('#CommercialConsent').count(), 0, 'commercial configuration removed from editor');
        assert.deepEqual(errors, [], 'no browser runtime errors');
        console.log('PASS modal: existing contacts selectable by default, single yes/no filter, deduplicated full selection, saved message, encoded links, manual reactivation, next, close/reopen, reload, resume, skip, history and CSRF. WhatsApp was intercepted.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
