const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_CORE || 'playwright-core');
(async () => {
    const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(() => {
        window.testLinks = [];
        const fake = { closed: false, focus() {}, close() { this.closed = true; } };
        Object.defineProperty(fake, 'location', { set(value) { window.testLinks.push(String(value)); } });
        window.open = () => window.testBlocked ? null : fake;
    });
    const ready = () => page.waitForFunction(() => document.querySelector('#waStart') && !document.querySelector('#waStart').disabled);
    const openModal = async () => { await ready(); await page.click('#waStart'); await page.waitForSelector('#waWorkspace.show'); await ready(); };
    try {
        await page.goto('http://127.0.0.1:5187/Records?StatusIds=1&WhatsAppFilter=no'); await ready();
        assert.equal(await page.locator('#btnExportFiltered svg').count(), 1, 'filtered export uses an Excel icon');
        assert.equal((await page.locator('#btnExportFiltered').innerText()).trim(), '', 'export button contains only the icon');
        assert.equal(await page.locator('#btnExportProspects, #btnExportForPhone').count(), 0, 'extra export options removed');
        const exportDownload = page.waitForEvent('download');
        await page.click('#btnExportFiltered');
        assert.match((await exportDownload).suggestedFilename(), /\.csv$/i, 'vendor can download CSV without audit access');
        await page.goto('http://127.0.0.1:5187/Records/Edit/1');
        assert.equal(await page.locator('#recordStatus').inputValue(), '1', 'edit preserves selected state');
        assert.match(await page.locator('#recordStatusBadge').getAttribute('class'), /text-bg-primary/, 'initial badge uses catalog color');
        await page.click('#recordStatusButton');
        await page.check('.js-record-status[value="2"]');
        assert.equal(await page.locator('#recordStatus').inputValue(), '2', 'dropdown updates bound form value');
        assert.match(await page.locator('#recordStatusBadge').getAttribute('class'), /text-bg-danger/, 'rejection uses catalog color');
        await page.click('#recordStatusButton');
        await page.check('.js-record-status[value="3"]');
        assert.match(await page.locator('#recordStatusBadge').getAttribute('class'), /text-bg-warning/, 'interested uses catalog color');
        assert.equal(await page.locator('.js-record-status:checked').count(), 1, 'edit allows one state');
        assert.equal(await page.locator('#recordStatus').inputValue(), '3', 'interested state is submitted');
        assert.equal(await page.locator('#recordStatusBadge').innerText(), 'Interesado', 'color badge follows selected state');
        await page.goto('http://127.0.0.1:5187/Records?StatusIds=1&WhatsAppFilter=no'); await ready();
        assert.equal(await page.locator('#ConsentFilter').count(), 0, 'commercial filter is removed');
        assert.equal(await page.locator('#WhatsAppFilter').count(), 0, 'reactivation combo is removed');
        assert.equal(await page.locator('#waSelectAll, .wa-select').count(), 0, 'row selection checkboxes are removed');
        assert.equal(await page.locator('[data-wa-record]').count(), 4, 'default dates and status filter limit displayed records');
        assert.match(await page.locator('#waStart').textContent(), /WhatsApp masivo \(2\)/, 'duplicate phones count once');
        await openModal();
        assert.equal(await page.locator('#waContacts .list-group-item').count(), 2, 'modal lists all selected contacts before starting');
        await page.fill('#waMessage', 'Hola & reactivación 🧪\nConsulta envío a tu ciudad.');
        await page.click('#waSaveMessage');
        await page.waitForFunction(() => document.querySelector('#waFeedback').textContent === 'Mensaje guardado.');
        await page.evaluate(() => window.testBlocked = true);
        await page.click('#waConfirm');
        await page.waitForSelector('#waFeedback a');
        assert.match(await page.locator('#waFeedback a').getAttribute('href'), /^https:\/\/web\.whatsapp\.com\/send\?/, 'popup-blocked fallback remains usable');
        await page.evaluate(() => window.testBlocked = false);
        await page.click('#waOpen');
        await page.waitForFunction(() => window.testLinks.length === 1 && !document.querySelector('#waSent').disabled);
        const firstLink = await page.evaluate(() => window.testLinks[0]);
        assert.equal(new URL(firstLink).searchParams.get('text'), 'Hola & reactivación 🧪\nConsulta envío a tu ciudad.');
        assert.match(await page.locator('#waProgress').textContent(), /0 de 2 enviados/);
        assert.equal(await page.locator('.wa-row-state[data-sent="yes"]').count(), 0, 'opening link does not set reactivated yes');
        await page.screenshot({ path: process.env.WA_SCREENSHOT || 'whatsapp-modal-desktop.png', fullPage: true });
        await page.setViewportSize({ width: 390, height: 844 });
        await page.screenshot({ path: (process.env.WA_SCREENSHOT || 'whatsapp-modal-desktop.png').replace('desktop', 'mobile'), fullPage: true });
        await page.setViewportSize({ width: 1440, height: 1000 });
        await page.click('#waSent');
        await page.waitForFunction(() => document.querySelector('#waProgress').textContent.includes('1 de 2 enviados') && window.testLinks.length === 2);
        let secondLink = await page.evaluate(() => window.testLinks[1]);
        assert.notEqual(new URL(firstLink).searchParams.get("phone"), new URL(secondLink).searchParams.get("phone"));
        assert.equal(await page.locator('#waContacts .text-bg-success').count(), 1, 'modal marks sent item and keeps full queue');
        assert.ok(await page.locator('.wa-row-state[data-sent="yes"]').count() > 0, 'confirmed send updates reactivated immediately');
        assert.equal(await page.locator('#waMessage').isEnabled(), true, 'message remains editable during an active campaign');
        await page.fill('#waMessage', 'Mensaje actualizado 🧪');
        assert.equal(await page.locator('#waSent').isDisabled(), true, 'unsaved edits cannot be declared sent');
        await page.click('#waSaveMessage');
        await page.waitForFunction(() => document.querySelector('#waFeedback').textContent.includes('Mensaje actualizado'));
        assert.equal(await page.locator('#waSent').isDisabled(), true, 'edited pending message requires reopening the chat');
        await page.click('#waOpen');
        await page.waitForFunction(() => window.testLinks.length === 3 && !document.querySelector('#waSent').disabled);
        secondLink = await page.evaluate(() => window.testLinks[2]);
        assert.equal(new URL(secondLink).hostname, 'web.whatsapp.com');
        assert.equal(new URL(secondLink).searchParams.get('text'), 'Mensaje actualizado 🧪');
        await page.locator('#waWorkspace .btn-close').click();
        await page.waitForSelector('#waWorkspace', { state: 'hidden' });
        await openModal();
        assert.match(await page.locator('#waProgress').textContent(), /1 de 2 enviados/);
        assert.equal(await page.locator('#waContacts .list-group-item').count(), 2, 'closing modal preserves selection');
        await page.reload(); await ready();
        assert.equal(await page.evaluate(() => window.testLinks.length), 0, 'reload never opens WhatsApp');
        await openModal();
        assert.match(await page.locator('#waProgress').textContent(), /1 de 2 enviados/);
        await page.click('#waPause'); await page.waitForSelector('#waContinue:not([hidden])');
        await page.reload(); await openModal();
        await page.click('#waContinue');
        await page.waitForFunction(() => window.testLinks.length === 1 && !document.querySelector('#waSkip').disabled);
        assert.equal(await page.evaluate(() => window.testLinks[0]), secondLink, 'resume returns to the stored pending number');
        await page.click('#waSkip');
        await page.waitForFunction(() => document.querySelector('#waProgress').textContent.includes('Completado'));
        const noToken = await page.request.post('http://127.0.0.1:5187/Records?handler=WhatsAppMessage', { data: { message: 'missing CSRF' } });
        assert.equal(noToken.status(), 400);
        await page.goto('http://127.0.0.1:5187/Records?WhatsAppFilter=yes'); await ready();
        assert.equal(await page.locator('#WhatsAppFilter').count(), 0, 'old links do not restore a hidden reactivation filter');
        assert.ok(await page.locator('.wa-row-state[data-sent="yes"]').count() > 0, 'reactivation history remains visible');
        assert.ok(await page.locator('.wa-row-state[data-sent="no"]').count() > 0, 'old yes query no longer hides other records');
        await page.locator('tr:has(.wa-row-state[data-sent="yes"]) .wa-history').first().click();
        await page.waitForFunction(() => document.querySelector('#waHistoryBody').textContent.includes('Hola & reactivación 🧪'));
        const today = new Date().toLocaleDateString('en-CA');
        await page.goto(`http://127.0.0.1:5187/Records?StatusIds=1&Search=Cliente%20de%20prueba%20A&FromDate=${today}&ToDate=${today}`); await ready();
        assert.match(await page.locator('#waStart').textContent(), /WhatsApp masivo \(1\)/, 'bulk count follows status, search and date filters');
        await page.fill('#Search', 'this search has not been applied');
        await openModal();
        assert.equal(await page.locator('#waContacts .list-group-item').count(), 1, 'draft uses the applied filter');
        await page.route('**/*handler=WhatsAppCreate*', async route => {
            const input = route.request().postDataJSON();
            await route.continue({ postData: JSON.stringify({ ...input, ids: [5, 7] }) });
        });
        await page.click('#waConfirm');
        await page.waitForSelector('#waSent:not([hidden])'); await ready();
        assert.equal(await page.locator('#waContacts .list-group-item').count(), 1, 'server derives recipients from filters despite unrelated submitted IDs');
        assert.match(await page.locator('#waCurrent').textContent(), /51900000001/);
        await page.unroute('**/*handler=WhatsAppCreate*');
        await page.goto('http://127.0.0.1:5187/Records?StatusIds=3'); await ready();
        await openModal();
        assert.match(await page.locator('#waCurrent').textContent(), /51900000001/, 'changing filters preserves the pending campaign');
        await page.click('#waSkip');
        await page.waitForFunction(() => document.querySelector('#waProgress').textContent.includes('Completado'));
        const oldDay = new Date(); oldDay.setDate(oldDay.getDate() - 5);
        const oldDate = oldDay.toLocaleDateString('en-CA');
        await page.goto(`http://127.0.0.1:5187/Records?StatusIds=1&FromDate=${oldDate}&ToDate=${oldDate}`); await ready();
        await openModal();
        await page.click('#waConfirm');
        await page.waitForSelector('#waSent:not([hidden])'); await ready();
        assert.equal(await page.locator('#waContacts .list-group-item').count(), 1, 'date range excludes contacts outside the chosen day');
        assert.match(await page.locator('#waCurrent').textContent(), /51900000005/);
        await page.click('#waSkip');
        await page.waitForFunction(() => document.querySelector('#waProgress').textContent.includes('Completado'));
        await page.goto('http://127.0.0.1:5187/Records?Search=does-not-exist');
        await page.waitForFunction(() => document.querySelector('#waStart').textContent.includes('(0)'));
        assert.equal(await page.locator('#waStart').isDisabled(), true, 'empty filters cannot start a campaign');
        await page.goto('http://127.0.0.1:5187/Records/Edit/4');
        assert.equal(await page.locator('#CommercialConsent').count(), 0, 'commercial configuration removed from editor');
        assert.deepEqual(errors, [], 'no browser runtime errors');
        console.log('PASS modal: server-side applied filters, no selection checkboxes, no reactivation combo, deduplicated recipients, saved message, encoded links, manual reactivation, next, close/reopen, reload, resume, skip, history and CSRF. WhatsApp was intercepted.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
